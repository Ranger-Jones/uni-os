export default async function (win, out) {
  await win.getByText('Create your first semester').click()
  await win.getByRole('button', { name: 'Create semester' }).click()
  await win.getByText('Add a course').click()
  await win.getByLabel('Course name').fill('Analysis I')
  await win.getByRole('button', { name: 'Create course' }).click()
  await win.getByRole('tab', { name: 'Notes' }).click()
  await win.locator('main').getByRole('button', { name: 'New page' }).click()
  await win.waitForTimeout(500)
  await win.getByPlaceholder('Untitled').fill('Vorlesung 1: Folgen')
  await win.keyboard.press('Enter')
  await win.keyboard.type('Eine Folge konvergiert gegen den Grenzwert a, wenn für jedes Epsilon ein N existiert.')
  await win.keyboard.press('Enter')
  await win.keyboard.type('# Cauchy-Folgen')
  await win.keyboard.press('Enter')
  await win.keyboard.type('- [ ] Übungsblatt 1 rechnen')
  await win.waitForTimeout(900)
  await win.screenshot({ path: `${out}-page.png` })
  await win.keyboard.press('Meta+k')
  await win.keyboard.type('grenzw')
  await win.waitForTimeout(500)
  await win.screenshot({ path: `${out}-palette.png` })
  await win.keyboard.press('Escape')
}
